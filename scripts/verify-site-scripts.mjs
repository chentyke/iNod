import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {createHash, webcrypto} from 'node:crypto';
const source = readFileSync(new URL('../Sources/NodeSeekClient/Website/AccountScripts.swift',import.meta.url),'utf8');
const script = source.match(/static let request = #"""\n([\s\S]*?)\n    """#/)[1];
const AsyncFunction = Object.getPrototypeOf(async function(){}).constructor;
const run = new AsyncFunction('path','method','body','headers','fetch','location','navigator','localStorage','crypto',script);
const storage = new Map();
const localStorage = {getItem:key=>storage.get(key)??null,setItem:(key,value)=>storage.set(key,value),removeItem:key=>storage.delete(key)};
const origin = 'https://www.nodeseek.com';
const agent = 'NodeSeek script test';
let captured, reply = {success:true}, status = 200;
const fetch = async (path,options)=>{ captured={path,options};return {ok:status<400,status,headers:{get:()=>null},json:async()=>reply}; };
const request = async (path,method='GET',body='')=>JSON.parse(await run(path,method,body,{},fetch,{origin},{userAgent:agent},localStorage,webcrypto));
for (const [path,method,body] of [['/api/vote/info/456','GET',''],['/api/vote/voteforitem','POST','{"ids":[1,2]}'],['/api/stardust/send','POST','{"diff":5,"member_id":9,"ref_id":100}']]) {
  assert.equal((await request(path,method,body)).success,true);
  const expected=createHash('sha1').update([method,new URL(path,origin).href,agent,body].join('\n\n')).digest('hex');
  assert.equal(captured.options.headers['x-dynamic-sign'],expected);
  assert.equal(captured.options.credentials,'same-origin');
  assert.equal(captured.options.body,body||undefined);
}
await request('/api/account/find/test');
assert.equal(captured.options.headers['x-dynamic-sign'],undefined);
assert.match((await request('/api/invite/buyOne','POST','{"payment":"coin"}')).__error,/验证/);
storage.set('csrf_token','test-token');
await request('/api/invite/buyOne','POST','{"payment":"coin"}');
assert.equal(captured.options.headers['x-csrf-token'],'test-token');
assert.equal(captured.options.headers['x-csrf-challenge'],'simple-token');
status=403; reply={success:false,message:'请完成官网验证'};
assert.equal((await request('/api/vote/info/456')).__needsWebsite,true);
status=200;reply={success:false,message:'尚未开放'};
assert.equal((await request('/api/account/example')).__error,'尚未开放');
const htmlChallenge=JSON.parse(await run('/api/vote/info/456','GET','',{},async()=>({ok:false,status:403,headers:{get:()=>null},json:async()=>{throw new SyntaxError('HTML challenge');}}),{origin},{userAgent:agent},localStorage,webcrypto));
assert.equal(htmlChallenge.__needsWebsite,true);
const extract = (name, text = source) => text.match(new RegExp('static let '+name+' = #"""\\n([\\s\\S]*?)\\n    """#'))[1];
const action = new AsyncFunction('path','body','headers','fetch',extract('action'));
for (const code of [400,403,500]) {
  status=code;reply={success:false,message:'具体拒绝原因'};
  const result=JSON.parse(await action('/api/notification/message/send','{"receiverUid":9,"content":"test","markdown":false}',{},fetch));
  assert.equal(result.__error,'具体拒绝原因');
  assert.equal(result.__needsWebsite,code===403);
}
status=200;reply={success:true};
await action('/api/notification/message/markViewed?all=true','',{},fetch);
assert.equal(captured.options.body,undefined);
assert.equal(captured.options.headers['Content-Type'],undefined);
await request('/api/account/unbind-telegram','POST');
assert.equal(captured.options.body,undefined);
const avatar=new AsyncFunction('encoded','fetch',extract('uploadAvatar'));
assert.equal(JSON.parse(await avatar('AA==',fetch)).success,true);
assert.equal(captured.path,'/api/avatar/upload');
assert.deepEqual([...captured.options.body.keys()],['token','name','img']);
assert.equal(captured.options.body.get('token'),'123456798');
assert.equal(captured.options.body.get('name'),'avatar');
assert.equal(captured.options.body.get('img').type,'image/png');
assert.equal(captured.options.headers['x-csrf-challenge'],'simple-token');
const site=readFileSync(new URL('../Sources/NodeSeekClient/Website/SiteScripts.swift',import.meta.url),'utf8');
status=400;reply={success:false,message:'鸡腿不足'};
const post=new AsyncFunction('path','body','token','fetch',extract('post',site));
assert.equal(JSON.parse(await post('/api/statistics/like','{}','',fetch)).__error,'鸡腿不足');
const get=new AsyncFunction('path','fetch',extract('get',site));
assert.equal(JSON.parse(await get('/api/progress/today',fetch)).__error,'鸡腿不足');
const loginSource=readFileSync(new URL('../Sources/NodeSeekClient/Session/SignInScripts.swift',import.meta.url),'utf8');
const login=new AsyncFunction('body','token','fetch','location',extract('submit',loginSource));
status=200;reply={success:true,need2FA:true,otpSession:'example-session'};
